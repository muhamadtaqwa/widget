async function fetchJournalData() {
  const sintaId = inputs.sintaId.value;
  const issn = inputs.eissn.value;
  const sc_parsed = parseStatcounterUrl(inputs.statcounterUrl.value);
  const stid = sc_parsed.stid;
  const staccid = sc_parsed.staccid;
  const stlid = sc_parsed.stlid;
  const stsc = sc_parsed.stsc;

  if (!sintaId) {
    alert(i18n[window.APP_LANG || "en"].alertSintaId);
    return false;
  }

  try {
    const url = `/api/fetch?sinta=${encodeURIComponent(sintaId)}&issn=${encodeURIComponent(issn)}&stid=${encodeURIComponent(stid)}&staccid=${encodeURIComponent(staccid)}&stlid=${encodeURIComponent(stlid)}&stsc=${encodeURIComponent(stsc)}&scimago=${encodeURIComponent(inputs.scimagoId.value)}`;
    const response = await fetch(url);

    if (!response.ok) {
      throw new Error(`HTTP error! status: ${response.status}`);
    }

    const text = await response.text();
    let result;
    try {
      result = JSON.parse(text);
    } catch (e) {
      console.error("Invalid JSON response:", text);
      throw new Error("Server sent an invalid data format.");
    }

    if (result.success) {
      if (result.data.name) inputs.journalName.value = result.data.name;
      if (result.data.eissn && !inputs.eissn.value)
        inputs.eissn.value = result.data.eissn;

      fetchedStats.rank = result.data.rank;
      fetchedStats.impact = result.data.impact;
      fetchedStats.scholarId = result.data.scholarId;
      fetchedStats.citations = result.data.citations;
      fetchedStats.openAlexCitations = result.data.openAlexCitations || "0";

      if (result.data.scholarId && !inputs.scholarId.value) {
        inputs.scholarId.value = result.data.scholarId;
      }

      if (result.data.statcounterCount) {
        if (
          !inputs.statcounterCount.value ||
          inputs.statcounterCount.value === "0"
        ) {
          inputs.statcounterCount.value = result.data.statcounterCount;
        }
      }

      if (result.data.statcounterDebug) {
        console.warn("Statcounter debug:", result.data.statcounterDebug);
      }

      if (result.data.scopus && result.data.scopus !== "0") {
        inputs.scopusCitations.value = result.data.scopus;
      }

      return true;
    } else {
      alert("Failed to fetch data: " + (result.error || "An error occurred"));
      return false;
    }
  } catch (error) {
    console.error(error);
    alert("An error occurred while contacting the server.");
    return false;
  }
}


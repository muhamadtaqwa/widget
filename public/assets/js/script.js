function formatNumber(num) {
  if (!num) return "0";
  let n = parseFloat(num.toString().replace(/,/g, ""));
  if (isNaN(n)) return num;

  if (n >= 1000000) {
    return (n / 1000000).toFixed(1).replace(/\.0$/, "") + "M";
  }
  if (n >= 1000) {
    return (n / 1000).toFixed(1).replace(/\.0$/, "") + "K";
  }
  return n.toString();
}

function parseStatcounterUrl(urlStr) {
  const result = { stid: "", staccid: "", stlid: "", stsc: "" };
  if (!urlStr) return result;
  try {
    const pathMatch = urlStr.match(/\/p(\d+)/);
    if (pathMatch) result.stid = pathMatch[1];

    const qStart = urlStr.indexOf("?");
    if (qStart !== -1) {
      const params = new URLSearchParams(urlStr.slice(qStart + 1));

      if (!result.stid) {
        result.stid = params.get("project_id") || params.get("project") || "";
      }

      result.staccid = params.get("account_id") || "";
      result.stlid = params.get("login_id") || "";
      result.stsc = params.get("code") || params.get("security") || "";
    }
  } catch (e) {}
  return result;
}


function initPremiumModal() {
  const modal = document.getElementById("premiumModal");
  const trigger = document.getElementById("premiumTrigger");
  const closeBtn = document.getElementById("closeModal");

  if (!modal) return;

  const now = new Date().getTime();
  const lastShown = sessionStorage.getItem("premium_modal_last_shown");
  const expiryTime = 1 * 60 * 1000;

  if (!lastShown || now - lastShown > expiryTime) {
    setTimeout(() => {
      modal.classList.remove("hidden");
      document.body.style.overflow = "hidden";
      sessionStorage.setItem("premium_modal_last_shown", now);
    }, 1500);
  }

  if (trigger) {
    trigger.addEventListener("click", (e) => {
      e.preventDefault();
      modal.classList.remove("hidden");
      document.body.style.overflow = "hidden";
    });
  }

  if (closeBtn) {
    closeBtn.addEventListener("click", () => {
      modal.classList.add("hidden");
      document.body.style.overflow = "";
    });

    modal.addEventListener("click", (e) => {
      if (e.target === modal) {
        modal.classList.add("hidden");
        document.body.style.overflow = "";
      }
    });
  }
}


function generateIframeHTML() {
  const widgetType = document.querySelector(
    'input[name="widgetType"]:checked',
  ).value;
  const sc_parsed = parseStatcounterUrl(inputs.statcounterUrl.value);
  const baseUrl = window.location.origin + "/";

  if (widgetType === "chart") {
    const color = inputs.primaryColor.value.replace("#", "");
    const issn = showOpenAlexChart.checked ? inputs.eissn.value : "";
    const gsId = showScholarChart.checked
      ? inputs.scholarId.value || fetchedStats.scholarId
      : "";
    const sintaId = inputs.sintaId.value;

    return `<iframe src="${baseUrl}widgets/graph?issn=${issn}&id=${gsId}&sinta=${sintaId}&warna=${color}" width="100%" height="600" frameborder="0" scrolling="no" style="border:0; overflow:hidden; min-height: 500px;"></iframe>`;
  }

  if (widgetType === "scimago") {
    const scimagoId = inputs.scimagoId.value;
    const name = inputs.journalName.value;
    const color = inputs.primaryColor.value.replace("#", "");

    const quartileData = [];
    document.querySelectorAll("#quartileRows .data-row").forEach((row) => {
      const cat = row.querySelector(".q-category")?.value?.trim();
      const q = row.querySelector(".q-value")?.value?.trim();
      if (cat && q) quartileData.push({ category: cat, quartile: q });
    });

    const sjrData = [];
    document.querySelectorAll("#sjrRows .data-row").forEach((row) => {
      const year = row.querySelector(".sjr-year")?.value?.trim();
      const val = row.querySelector(".sjr-value")?.value?.trim();
      if (year && val) sjrData.push({ year, value: val });
    });

    const manualData = btoa(
      unescape(
        encodeURIComponent(JSON.stringify({ q: quartileData, s: sjrData })),
      ),
    );

    let h = 480;
    if (!name) h -= 40;

    const rowCount = Math.max(quartileData.length, sjrData.length);
    if (rowCount > 5) h += (rowCount - 5) * 35;

    return `<iframe src="${baseUrl}widgets/scimago?id=${scimagoId}&warna=${color}&name=${encodeURIComponent(name)}&data=${manualData}" width="100%" height="${h}" frameborder="0" scrolling="no" style="border:0; overflow:hidden;"></iframe>`;
  }

  if (widgetType === "indexing") {
    const color = inputs.primaryColor.value.replace("#", "");
    const params = new URLSearchParams();
    params.append("warna", color);

    const indexingKeys = {
      sinta: "urlSinta",
      scopus: "urlScopus",
      scimago: "urlScimago",
      doaj: "urlDOAJ",
      dimensions: "urlDimensions",
      garuda: "urlGaruda",
      scholar: "urlScholar",
      scilit: "urlScilit",
    };

    Object.entries(indexingKeys).forEach(([paramKey, inputKey]) => {
      const inputEl = inputs[inputKey];
      if (inputEl && inputEl.value) {
        params.append(paramKey, inputEl.value);
      }
    });
    return `<iframe src="${baseUrl}widgets/indexing?${params.toString()}" width="100%" height="380" frameborder="0" scrolling="no" style="border:0; overflow:hidden;"></iframe>`;
  }

  if (widgetType === "tools") {
    const color = inputs.primaryColor.value.replace("#", "");
    const params = new URLSearchParams();
    params.append("warna", color);

    const toolsKeys = {
      turnitin: "urlTurnitin",
      mendeley: "urlMendeley",
      grammarly: "urlGrammarly",
      quillbot: "urlQuillbot",
    };

    Object.entries(toolsKeys).forEach(([paramKey, inputKey]) => {
      const inputEl = inputs[inputKey];
      if (inputEl && inputEl.value) {
        params.append(paramKey, inputEl.value);
      }
    });
    return `<iframe src="${baseUrl}widgets/tools?${params.toString()}" width="100%" height="220" frameborder="0" scrolling="no" style="border:0; overflow:hidden;"></iframe>`;
  }

  if (widgetType === "template") {
    const color = inputs.primaryColor.value.replace("#", "");
    const name = inputs.journalName.value;

    const templateData = [];
    document.querySelectorAll("#templateRows .data-row").forEach((row) => {
      const type = row.querySelector(".t-type")?.value;
      const label = row.querySelector(".t-label")?.value?.trim();
      const url = row.querySelector(".t-url")?.value?.trim();
      if (label && url) {
        templateData.push({ type, label, url });
      }
    });

    const encodedData = btoa(
      unescape(encodeURIComponent(JSON.stringify(templateData))),
    );

    let h = 80 + templateData.length * 70;
    if (h < 120) h = 120;

    return `<iframe src="${baseUrl}widgets/templates?data=${encodedData}&warna=${color}&name=${encodeURIComponent(name)}" width="100%" height="${h}" frameborder="0" scrolling="no" style="border:0; overflow:hidden;"></iframe>`;
  }

  const dataObj = {
    n: inputs.journalName.value,
    s: inputs.sintaId.value,
    g: inputs.scholarId.value || fetchedStats.scholarId,
    c: inputs.scopusCitations.value,
    i: inputs.eissn.value,
    ti: sc_parsed.stid,
    ai: sc_parsed.staccid,
    li: sc_parsed.stlid,
    sc: sc_parsed.stsc,
    ct: inputs.statcounterCount.value,
    st:
      document.querySelector('input[name="tableStyle"]:checked')?.value ||
      "text",
    p: inputs.primaryColor.value,
    t: inputs.textColor.value,
  };

  const encodedData = btoa(
    unescape(encodeURIComponent(JSON.stringify(dataObj))),
  );

  const showScopus = dataObj.c && dataObj.c !== "0";
  const showOpenAlex = dataObj.i;
  const showStatcounter = dataObj.ti;

  let cardRows = 3;
  if (showScopus) cardRows++;
  if (showOpenAlex) cardRows++;
  if (showStatcounter) cardRows++;

  let rows = Math.ceil(cardRows / 3);
  if (cardRows <= 4) rows = 1;
  let height = rows * 180 + 100;
  if (!inputs.journalName.value) height -= 40;
  if (height > 600) height = 600;
  if (height < 200) height = 200;

  return `<iframe src="${baseUrl}widgets/statistik?d=${encodedData}" width="100%" height="${height}" frameborder="0" scrolling="no" style="border:0; overflow:hidden;"></iframe>`;
}


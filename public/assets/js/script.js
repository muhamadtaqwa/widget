function makeQuartileSelect(selectedVal) {
  const opts = ["Q1", "Q2", "Q3", "Q4"]
    .map(
      (q) =>
        `<option value="${q}"${q === selectedVal ? " selected" : ""}>${q}</option>`,
    )
    .join("");
  return `<select class="q-value" aria-label="Quartile">${opts}</select>`;
}

